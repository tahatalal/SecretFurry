export interface MarkingDef {
  readonly id: string;
  readonly name: string;
  readonly sprite: Sprite;
}

export const MARKINGS: readonly MarkingDef[] = [
  { id: "none", name: "Plain", sprite: NONE },
  { id: "blaze", name: "Blaze", sprite: BLAZE },
  { id: "mask", name: "Mask", sprite: MASK },
  { id: "cheeks", name: "Cheeks", sprite: CHEEKS },
  { id: "spots", name: "Spots", sprite: SPOTS },
  { id: "stripes", name: "Stripes", sprite: STRIPES },
  { id: "brow", name: "Brow", sprite: BROW },
] as const;

export function markingById(id: string): MarkingDef {
  return MARKINGS.find((m) => m.id === id) ?? MARKINGS[0]!;
}
