/* ---------------------------------------------------------------------------
   Marking overlays. Painted on top of a head, so they only use one key:

     A  accent color (the marking color the player picked)

   These respect the shared anatomy documented in heads.ts: they never paint
   over the eye boxes (rows 12-17, cols 6-11 and 20-25) and they stay inside
   cols 3-28 so no marking spills off a narrow head.
--------------------------------------------------------------------------- */

